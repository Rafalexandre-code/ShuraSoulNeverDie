using System;
using System.Collections.Concurrent;
using System.Collections.Generic;
using System.IO;
using System.Net;
using System.Net.Sockets;
using System.Security.Cryptography;
using System.Text;
using System.Threading;

namespace Shura
{
    /// <summary>
    /// A tiny HTTP + WebSocket server on plain sockets (no packages, no admin rights):
    /// it serves the browser client's files from a folder and upgrades "/ws" connections to
    /// WebSockets. Runs on background threads; the game reads <see cref="Inbox"/> on the main
    /// thread and sends with <see cref="Broadcast"/>/<see cref="Send"/>. Nothing here touches
    /// Unity APIs.
    /// </summary>
    public sealed class WebServer
    {
        public enum EventKind
        {
            Connected,
            Message,
            Disconnected,
        }

        public struct Event
        {
            public EventKind kind;
            public int client;
            public string text;
            public string address;
        }

        sealed class Client
        {
            public int id;
            public TcpClient tcp;
            public NetworkStream stream;
            public readonly BlockingCollection<byte[]> outbox = new BlockingCollection<byte[]>(new ConcurrentQueue<byte[]>());
            public volatile bool open = true;
        }

        const string WsGuid = "258EAFA5-E914-47DA-95CA-C5AB0DC85B11";
        const int MaxQueued = 12;

        readonly ConcurrentDictionary<int, Client> clients = new ConcurrentDictionary<int, Client>();
        readonly string webRoot;
        TcpListener listener;
        Thread acceptThread;
        volatile bool running;
        int nextId;

        public readonly ConcurrentQueue<Event> Inbox = new ConcurrentQueue<Event>();
        public int Port { get; private set; }
        public string Error { get; private set; }

        volatile Dictionary<string, byte[]> dynamicFiles = new Dictionary<string, byte[]>();

        /// <summary>Files generated by the game (the arena image), served by path. Swapped atomically.</summary>
        public Dictionary<string, byte[]> Dynamic
        {
            get => dynamicFiles;
            set
            {
                dynamicFiles = value;
                DynamicChanged?.Invoke(value);
            }
        }

        /// <summary>Raised (on the caller's thread) when the generated files change: tunnels forward them.</summary>
        public event Action<Dictionary<string, byte[]>> DynamicChanged;

        // ── Pipes: players who reach the game through a tunnel (Steam) instead of a socket ──

        /// <summary>The far end of a tunnelled WebSocket: delivers text to that player, or hangs up.</summary>
        public interface IPipe
        {
            void Deliver(string text);
            void Close();
        }

        readonly ConcurrentDictionary<int, IPipe> pipes = new ConcurrentDictionary<int, IPipe>();

        /// <summary>A tunnelled player opened their connection: they look like any browser to the game.</summary>
        public int AttachPipe(IPipe pipe, string address)
        {
            int id = Interlocked.Increment(ref nextId);
            pipes[id] = pipe;
            Inbox.Enqueue(new Event { kind = EventKind.Connected, client = id, address = address });
            return id;
        }

        public void PipeMessage(int id, string text)
        {
            if (pipes.ContainsKey(id)) Inbox.Enqueue(new Event { kind = EventKind.Message, client = id, text = text });
        }

        public void DetachPipe(int id)
        {
            if (pipes.TryRemove(id, out _)) Inbox.Enqueue(new Event { kind = EventKind.Disconnected, client = id });
        }

        public WebServer(string webRoot)
        {
            this.webRoot = webRoot;
        }

        public bool Start(int port)
        {
            try
            {
                listener = new TcpListener(IPAddress.Any, port);
                listener.Start();
                Port = port;
                running = true;
                acceptThread = new Thread(AcceptLoop) { IsBackground = true, Name = "Shura.Web.Accept" };
                acceptThread.Start();
                return true;
            }
            catch (Exception e)
            {
                Error = e.Message;
                running = false;
                return false;
            }
        }

        public void Stop()
        {
            running = false;
            try { listener?.Stop(); } catch { /* already closed */ }
            foreach (Client c in clients.Values) Close(c);
            clients.Clear();
            foreach (IPipe p in pipes.Values) p.Close();
            pipes.Clear();
        }

        public void Send(int id, string text)
        {
            if (clients.TryGetValue(id, out Client c)) Enqueue(c, Frame(text));
            else if (pipes.TryGetValue(id, out IPipe p)) p.Deliver(text);
        }

        public void Broadcast(string text)
        {
            foreach (IPipe p in pipes.Values) p.Deliver(text);
            if (clients.IsEmpty) return;
            byte[] frame = Frame(text);
            foreach (Client c in clients.Values) Enqueue(c, frame);
        }

        public void Kick(int id)
        {
            if (clients.TryGetValue(id, out Client c)) Close(c);
            else if (pipes.TryGetValue(id, out IPipe p))
            {
                p.Close();
                DetachPipe(id);
            }
        }

        /// <summary>Local browsers connected right now (the Steam guest's proxy uses it).</summary>
        public int LocalClientCount => clients.Count;

        static void Enqueue(Client c, byte[] frame)
        {
            if (!c.open) return;
            // A slow client drops old snapshots instead of falling further behind.
            while (c.outbox.Count > MaxQueued && c.outbox.TryTake(out _)) { }
            c.outbox.TryAdd(frame);
        }

        // ── Accept & HTTP ───────────────────────────────────────────────────────────────

        void AcceptLoop()
        {
            while (running)
            {
                TcpClient tcp;
                try
                {
                    tcp = listener.AcceptTcpClient();
                }
                catch
                {
                    if (!running) return;
                    continue;
                }
                tcp.NoDelay = true;
                var t = new Thread(() => Handle(tcp)) { IsBackground = true, Name = "Shura.Web.Conn" };
                t.Start();
            }
        }

        void Handle(TcpClient tcp)
        {
            NetworkStream stream = null;
            try
            {
                stream = tcp.GetStream();
                stream.ReadTimeout = 15000;
                string head = ReadHead(stream);
                if (head == null)
                {
                    tcp.Close();
                    return;
                }
                string[] lines = head.Split(new[] { "\r\n" }, StringSplitOptions.None);
                string[] request = lines[0].Split(' ');
                if (request.Length < 2)
                {
                    tcp.Close();
                    return;
                }
                var headers = new Dictionary<string, string>(StringComparer.OrdinalIgnoreCase);
                for (int i = 1; i < lines.Length; i++)
                {
                    int colon = lines[i].IndexOf(':');
                    if (colon > 0) headers[lines[i].Substring(0, colon).Trim()] = lines[i].Substring(colon + 1).Trim();
                }
                string path = request[1];
                int q = path.IndexOf('?');
                if (q >= 0) path = path.Substring(0, q);

                if (path == "/ws" && headers.TryGetValue("Sec-WebSocket-Key", out string key))
                {
                    stream.ReadTimeout = Timeout.Infinite;
                    RunWebSocket(tcp, stream, key, (tcp.Client.RemoteEndPoint as IPEndPoint)?.Address.ToString() ?? "?");
                    return;
                }
                ServeFile(stream, Uri.UnescapeDataString(path));
            }
            catch
            {
                // A dropped browser tab is not an error worth reporting.
            }
            try { stream?.Close(); } catch { }
            try { tcp.Close(); } catch { }
        }

        static string ReadHead(NetworkStream stream)
        {
            var buffer = new List<byte>(1024);
            int b;
            while ((b = stream.ReadByte()) >= 0)
            {
                buffer.Add((byte)b);
                int n = buffer.Count;
                if (n >= 4 && buffer[n - 4] == 13 && buffer[n - 3] == 10 && buffer[n - 2] == 13 && buffer[n - 1] == 10)
                {
                    return Encoding.ASCII.GetString(buffer.ToArray(), 0, n - 4);
                }
                if (n > 16384) return null;
            }
            return null;
        }

        void ServeFile(NetworkStream stream, string path)
        {
            if (path == "/" || path.Length == 0) path = "/index.html";
            byte[] body = null;
            Dictionary<string, byte[]> dyn = Dynamic;
            if (dyn != null && dyn.TryGetValue(path, out byte[] generated)) body = generated;
            else if (!path.Contains("..") && webRoot != null)
            {
                string full = Path.Combine(webRoot, path.TrimStart('/').Replace('/', Path.DirectorySeparatorChar));
                if (File.Exists(full)) body = File.ReadAllBytes(full);
            }

            string status = body != null ? "200 OK" : "404 Not Found";
            if (body == null) body = Encoding.UTF8.GetBytes("Não encontrado");
            string type = ContentType(path);
            bool cacheable = path.StartsWith("/art/") || path.StartsWith("/sfx/") || path.StartsWith("/music/") || path.StartsWith("/fonts/") || path.StartsWith("/ui/");
            string header = "HTTP/1.1 " + status + "\r\nContent-Type: " + type + "\r\nContent-Length: " + body.Length +
                            "\r\nCache-Control: " + (cacheable ? "max-age=3600" : "no-cache") + "\r\nConnection: close\r\n\r\n";
            byte[] h = Encoding.ASCII.GetBytes(header);
            stream.Write(h, 0, h.Length);
            stream.Write(body, 0, body.Length);
            stream.Flush();
        }

        static string ContentType(string path)
        {
            string ext = Path.GetExtension(path).ToLowerInvariant();
            switch (ext)
            {
                case ".html": return "text/html; charset=utf-8";
                case ".js": return "application/javascript; charset=utf-8";
                case ".css": return "text/css; charset=utf-8";
                case ".png": return "image/png";
                case ".ogg": return "audio/ogg";
                case ".ttf": return "font/ttf";
                case ".json": return "application/json";
                case ".ico": return "image/x-icon";
                default: return "application/octet-stream";
            }
        }

        // ── WebSocket ───────────────────────────────────────────────────────────────────

        void RunWebSocket(TcpClient tcp, NetworkStream stream, string key, string address)
        {
            string accept;
            using (SHA1 sha = SHA1.Create())
            {
                accept = Convert.ToBase64String(sha.ComputeHash(Encoding.ASCII.GetBytes(key.Trim() + WsGuid)));
            }
            byte[] hs = Encoding.ASCII.GetBytes("HTTP/1.1 101 Switching Protocols\r\nUpgrade: websocket\r\nConnection: Upgrade\r\nSec-WebSocket-Accept: " + accept + "\r\n\r\n");
            stream.Write(hs, 0, hs.Length);

            var c = new Client { id = Interlocked.Increment(ref nextId), tcp = tcp, stream = stream };
            clients[c.id] = c;
            var sender = new Thread(() => SendLoop(c)) { IsBackground = true, Name = "Shura.Web.Send" };
            sender.Start();
            Inbox.Enqueue(new Event { kind = EventKind.Connected, client = c.id, address = address });
            try
            {
                var message = new List<byte>();
                while (running && c.open)
                {
                    if (!ReadFrame(stream, out int opcode, out bool fin, out byte[] payload)) break;
                    if (opcode == 8) break;
                    if (opcode == 9)
                    {
                        Enqueue(c, Frame(payload, 10));
                        continue;
                    }
                    if (opcode == 10) continue;
                    message.AddRange(payload);
                    if (!fin) continue;
                    Inbox.Enqueue(new Event { kind = EventKind.Message, client = c.id, text = Encoding.UTF8.GetString(message.ToArray()) });
                    message.Clear();
                }
            }
            catch
            {
                // Connection lost.
            }
            Close(c);
            clients.TryRemove(c.id, out _);
            Inbox.Enqueue(new Event { kind = EventKind.Disconnected, client = c.id });
        }

        static void SendLoop(Client c)
        {
            try
            {
                while (c.open)
                {
                    if (!c.outbox.TryTake(out byte[] frame, 500)) continue;
                    c.stream.Write(frame, 0, frame.Length);
                }
            }
            catch
            {
                c.open = false;
            }
        }

        static void Close(Client c)
        {
            if (!c.open) return;
            c.open = false;
            try { c.tcp.Close(); } catch { }
        }

        static bool ReadFrame(Stream s, out int opcode, out bool fin, out byte[] payload)
        {
            opcode = 0;
            fin = true;
            payload = null;
            int b0 = s.ReadByte();
            int b1 = s.ReadByte();
            if (b0 < 0 || b1 < 0) return false;
            fin = (b0 & 0x80) != 0;
            opcode = b0 & 0x0F;
            bool masked = (b1 & 0x80) != 0;
            long len = b1 & 0x7F;
            if (len == 126) len = (ReadByteOrThrow(s) << 8) | ReadByteOrThrow(s);
            else if (len == 127)
            {
                len = 0;
                for (int i = 0; i < 8; i++) len = (len << 8) | (uint)ReadByteOrThrow(s);
            }
            if (len > 1 << 20) return false;
            byte[] mask = new byte[4];
            if (masked) ReadExactly(s, mask, 4);
            payload = new byte[len];
            ReadExactly(s, payload, (int)len);
            if (masked)
            {
                for (int i = 0; i < payload.Length; i++) payload[i] ^= mask[i & 3];
            }
            return true;
        }

        static int ReadByteOrThrow(Stream s)
        {
            int b = s.ReadByte();
            if (b < 0) throw new EndOfStreamException();
            return b;
        }

        static void ReadExactly(Stream s, byte[] buffer, int count)
        {
            int read = 0;
            while (read < count)
            {
                int n = s.Read(buffer, read, count - read);
                if (n <= 0) throw new EndOfStreamException();
                read += n;
            }
        }

        public static byte[] Frame(string text) => Frame(Encoding.UTF8.GetBytes(text), 1);

        /// <summary>One unmasked server frame (opcode 1 text, 10 pong).</summary>
        public static byte[] Frame(byte[] payload, int opcode)
        {
            int len = payload.Length;
            int headerLen = len < 126 ? 2 : len <= 0xFFFF ? 4 : 10;
            var frame = new byte[headerLen + len];
            frame[0] = (byte)(0x80 | opcode);
            if (len < 126)
            {
                frame[1] = (byte)len;
            }
            else if (len <= 0xFFFF)
            {
                frame[1] = 126;
                frame[2] = (byte)(len >> 8);
                frame[3] = (byte)len;
            }
            else
            {
                frame[1] = 127;
                ulong l = (ulong)len;
                for (int i = 0; i < 8; i++) frame[2 + i] = (byte)(l >> (56 - 8 * i));
            }
            Buffer.BlockCopy(payload, 0, frame, headerLen, len);
            return frame;
        }

        /// <summary>For tests: decodes one masked client frame.</summary>
        public static bool TryDecodeClientFrame(byte[] data, out string text)
        {
            text = null;
            using (var ms = new MemoryStream(data))
            {
                if (!ReadFrame(ms, out int op, out _, out byte[] payload) || op != 1) return false;
                text = Encoding.UTF8.GetString(payload);
                return true;
            }
        }
    }
}
